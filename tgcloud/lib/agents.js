export const DEFAULT_AGENT_ID = 'chat';

export function getAgent(id) {
  return AGENTS.find((a) => a.id === id) ?? null;
}

export function getAgentOrDefault(id) {
  return getAgent(id) ?? getAgent(DEFAULT_AGENT_ID);
}

export function listAgentMeta() {
  return AGENTS.map(({ id, name, tagline, description, color }) => ({ id, name, tagline, description, color }));
}
