export function getAgentOrDefault(id) {
  const agent = getAgent(id);
  if (agent && agent.active !== false) return agent;
  return getAgent(DEFAULT_AGENT_ID);
}
export function listAgentMeta() {
  return AGENTS.map(({ id, name, tagline, description, color, active }) => ({
    id,
    name,
    tagline,
    description,
    color,
    active: active !== false,
  }));
}
